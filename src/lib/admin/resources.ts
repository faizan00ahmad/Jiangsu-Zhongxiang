export type Field = {
  key: string;
  label: T;
  type: FieldType;
  required?: boolean;
  options?: Opt[] | OptionSource;
  min?: number;
  max?: number;
  maxLen?: number;
  def?: unknown;
  help?: T;
  col?: ColStyle; // shown in the table
  full?: boolean; // spans the whole form row
  readOnly?: boolean; // shown, never written
  filter?: boolean; // gets a dropdown filter above the table
};

